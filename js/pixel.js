  /* ---------- Canvas-Helfer ---------- */
  function makeCanvas(w, h) {
    var c = document.createElement("canvas");
    c.width = w; c.height = h;
    return c;
  }

  var cache = {};   // key -> {canvas, w, h}
  var textCache = {};

  function renderMap(rows, palette) {
    var w = 0, r, c2;
    for (r = 0; r < rows.length; r++) w = Math.max(w, rows[r].length);
    var h = rows.length;
    var cv = makeCanvas(w, h), g = cv.getContext("2d");
    for (r = 0; r < h; r++) {
      var row = rows[r];
      for (c2 = 0; c2 < row.length; c2++) {
        var ch = row[c2];
        if (ch === ".") continue;
        var col = null;
        if (ch >= "0" && ch <= "9") col = (palette && palette[ch]) || PAL[ch];
        if (!col) continue;
        g.fillStyle = col;
        g.fillRect(c2, r, 1, 1);
      }
    }
    return { canvas: cv, w: w, h: h };
  }

  /* Sprite holen (gecacht). name = Sprite-Key, pal = Palettenname oder null */
  function sprite(name, pal) {
    var key = name + "|" + (pal || "");
    if (cache[key]) return cache[key];
    var palette = pal ? (PALETTES[pal] || null) : null;
    cache[key] = renderMap(SPR[name] || [], palette);
    return cache[key];
  }

  /* Font-Sprite-String: Zeichen -> 5x7, 1 Pixel Abstand */
  function textSprite(str, color, scale, tracking) {
    scale = scale || 1;
    tracking = tracking == null ? 1 : tracking;
    var key = str + "|" + color + "|" + scale + "|" + tracking;
    if (textCache[key]) return textCache[key];
    var chars = String(str).toUpperCase().split("");
    var w = Math.max(1, chars.length * (5 + tracking) - tracking);
    var h = 7;
    var cv = makeCanvas(w, h), g = cv.getContext("2d");
    g.fillStyle = color || "#fff";
    var x = 0;
    for (var i = 0; i < chars.length; i++) {
      var gl = FONT[chars[i]];
      if (!gl) gl = FONT["?"];
      for (var r = 0; r < 7; r++)
        for (var c = 0; c < 5; c++)
          if (gl[r][c] === "1") g.fillRect(x + c, r, 1, 1);
      x += 5 + tracking;
    }
    var out = { canvas: cv, w: w, h: h, scale: scale };
    textCache[key] = out;
    return out;
  }

  function textWidth(str, scale, tracking) {
    tracking = tracking == null ? 1 : tracking;
    return (String(str).length * (5 + tracking) - tracking) * (scale || 1);
  }

  /* Zeichen in ctx; x,y = linke obere Ecke; zentriert wenn align=center */
  function text(g, str, x, y, color, o) {
    o = o || {};
    var scale = o.scale || 1, tracking = o.tracking == null ? 1 : o.tracking;
    var t = textSprite(str, color, 1, tracking);
    var w = t.w * scale;
    if (o.align === "center") x = Math.round(x - w / 2);
    if (o.align === "right")  x = Math.round(x - w);
    g.drawImage(t.canvas, Math.round(x), Math.round(y), w, t.h * scale);
    return w;
  }

  /* Sprite in ctx zeichnen; cx,cy = Mittelpunkt */
  function draw(g, s, cx, cy, o) {
    o = o || {};
    var sc = o.scale || 1;
    var w = s.w * sc, h = s.h * sc;
    g.drawImage(s.canvas, Math.round(cx - w / 2), Math.round(cy - h / 2), w, h);
  }

  return {
    PAL: PAL, SPR: SPR, FONT: FONT,
    sprite: sprite, text: text, textWidth: textWidth, draw: draw,
    makeCanvas: makeCanvas
  };
